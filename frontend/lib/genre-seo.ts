export function slugifyGenre(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

export function findGenreBySlug(slug: string): GenreSeo | undefined {
  return GENRE_PAGES.find((g) => g.slug === slug);
}

export function findGenreByName(name: string): GenreSeo | undefined {
  return GENRE_PAGES.find((g) => g.name.toLowerCase() === name.toLowerCase());
}
